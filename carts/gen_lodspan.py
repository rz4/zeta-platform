#!/usr/bin/env python3
"""gen_lodspan.py -- writes carts/lodspan.zol: the mip level, once a span.

Build 89. The crown costs thirteen beats a textured pixel and FIVE of
them are the per-pixel mip level -- four gradient maxima and the pick.
At 43.2 MHz that is 3.3 Mpix/s, and a full 320x288 screen at 60 needs
5.53: you cannot texture the screen. Taking the level once per SPAN
instead, at the row's first covered pixel, drops the ladder to eight
beats and the rate to 5.4 -- essentially the whole screen.

This cart is the measurement, so it is deliberately the worst case: one
enormous textured plane running from under the camera to the horizon,
which is exactly where a span crosses mip levels and where holding one
level per row can be seen if it is going to be seen at all. Two objects,
identical but for the flag, so cross proves the law and the silicon
agree on BOTH paths in one run:

    the FAR plane   OBJ_LODSPAN -- one level per row
    the NEAR plane  per-pixel, the original law

Y and B tilt the gaze; the dpad turns and walks, as everywhere else.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from zeta import spec                                    # noqa: E402
from gen_tex import brick_page, page_words               # noqa: E402

ONE = 65536
PLANE_AT = 400
TEXIMG_AT = 6000
CP = 16


def plane(half, y, n=14):
    """An n x n TESSELLATED grid in the xz plane, uv stretched across the
    whole thing. Tessellated and not one big quad, because this machine
    has no near-plane clipping: a face with any vertex behind the eye is
    discarded WHOLE, so a single 80-unit quad under the camera vanishes
    entirely. The first version of this cart was two such quads and
    painted 1,280 pixels of 92,160 -- it measured nothing."""
    verts, uvs, faces = [], [], []
    for j in range(n + 1):
        for i in range(n + 1):
            verts += [int((i / n * 2 - 1) * half * ONE), int(y * ONE),
                      int((j / n * 2 - 1) * half * ONE)]
            uvs.append(int(i / n * 31) | (int(j / n * 31) << 8))
    for j in range(n):
        for i in range(n):
            a = j * (n + 1) + i
            b, c, d = a + 1, a + 1 + (n + 1), a + (n + 1)
            faces += [(a, c, b, 0xFFFFFF), (a, d, c, 0xFFFFFF)]
    assert len(verts) // 3 <= spec.MESH_NV_MAX
    return verts, uvs, faces


def mesh_words(verts, uvs, faces):
    w = [len(verts) // 3, len(faces)] + verts + uvs
    for a, b, c, col in faces:
        w += [a | (b << 10) | (c << 20), col]
    return w


def main():
    verts, uvs, faces = plane(40, 0)
    m = mesh_words(verts, uvs, faces)
    lines = [f".data {PLANE_AT + o} "
             + " ".join(str(spec.s32(v)) for v in m[o:o + 12])
             for o in range(0, len(m), 12)]

    page = page_words(brick_page())
    pg = [f".data {TEXIMG_AT + o} "
          + " ".join(str(spec.s32(v)) for v in page[o:o + 12])
          for o in range(0, len(page), 12)]
    assert TEXIMG_AT + len(page) <= spec.DMEM_WORDS

    SPAN = spec.OBJ_CULL | spec.OBJ_TEX | spec.OBJ_TINT | spec.OBJ_LODSPAN
    PIX = spec.OBJ_CULL | spec.OBJ_TEX | spec.OBJ_TINT

    out = ["; lodspan.zol -- GENERATED by gen_lodspan.py, do not edit",
           "; two identical planes, one per-span mip and one per-pixel:",
           "; cross proves both ladders at once.",
           "",
           ".const PAD 1",
           f".data {spec.CAM_X} 0 262144 0 0     ; eye 4 units up",
           f".data {spec.CAM_PITCH} 40",
           f".data {spec.TEX_SRC} {TEXIMG_AT}",
           f".data {spec.FOG_RGB} 0x{spec.CLEAR_RGB:06X}",
           f".data {spec.FOG_NEAR} 12288",
           f".data {spec.FOG_SHIFT} 10",
           "",
           f".data {spec.OL_BASE} 2"
           f" {PLANE_AT} 0 0 {80 * ONE} 0 {SPAN}"
           f" {PLANE_AT} 0 0 0 0 {PIX}",
           ""]
    out += lines + [""] + pg + [""]
    out += ["load PAD", "push 8", "and", "jz g_r",
            f"load {spec.CAM_YAW}", "push 8", "sub", "push 1023", "and",
            f"store {spec.CAM_YAW}", "g_r:",
            "load PAD", "push 4", "and", "jz g_l",
            f"load {spec.CAM_YAW}", "push 8", "add", "push 1023", "and",
            f"store {spec.CAM_YAW}", "g_l:",
            "load PAD", f"push {spec.PAD_Y}", "and", "jz g_u",
            f"load {CP}", "push 3", "sub", f"store {CP}", "g_u:",
            "load PAD", f"push {spec.PAD_B}", "and", "jz g_d",
            f"load {CP}", "push 3", "add", f"store {CP}", "g_d:",
            f"load {CP}", "push 1023", "and", f"store {spec.CAM_PITCH}",
            "load PAD", "push 1", "and", "jz g_f",
            f"load {spec.CAM_Z}", "push 26214", "add",
            f"store {spec.CAM_Z}", "g_f:",
            "load PAD", "push 2", "and", "jz g_b",
            f"load {spec.CAM_Z}", "push 26214", "sub",
            f"store {spec.CAM_Z}", "g_b:",
            "halt"]
    (HERE / "lodspan.zol").write_text("\n".join(out) + "\n")
    print(f"wrote lodspan.zol: 2 planes ({len(m)}w mesh), "
          f"span flag {SPAN}, per-pixel {PIX}")


if __name__ == "__main__":
    main()
