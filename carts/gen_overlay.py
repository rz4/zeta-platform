#!/usr/bin/env python3
"""gen_overlay.py -- writes carts/overlay.zol: a cart bigger than IMEM.

IMEM holds 4,096 instructions. That was the ceiling on how complicated a
game could be -- not how much world it had (the mover and the card made
content unbounded long ago) but how much PROGRAM. This removes it.

The cart carries THREE separate programs in its CRAM segment and runs
them one after another, paging each into IMEM as it goes. Only one is
ever resident. On screen each paints its own full-frame colour and its
own number of bars, so you can see the machine become a different
program every two seconds:

    GREEN  three bars      program one
    RED    five bars       program two
    YELLOW seven bars      program three

and then round again, forever. Nothing about the picture is shared
between them -- they are different programs that happen to run on the
same machine, in sequence, without the machine stopping.

The safety is the frame model rather than a rule: the swap happens after
the VM halts and every frame begins at PC 0, so a program asking to be
replaced always finishes its own frame first.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from zeta import spec                                    # noqa: E402

DL = spec.DL_BASE
PHASE = 700            # which program should run next (survives the swap:
                       # DMEM is untouched by an overlay)
BANK_AT = 1000         # where the three programs live in CRAM
BANK_STRIDE = 256

STYLES = [(0x20B040, 3), (0xC42020, 5), (0xE6C010, 7)]


def program(idx):
    """One of the three: paint, count down, then page in the next."""
    colour, bars = STYLES[idx]
    nxt = (idx + 1) % len(STYLES)
    L = []
    a = L.append
    # ---- count this program's remaining frames -------------------------
    a(f"load {PHASE}")
    a("push 1")
    a("add")
    a(f"store {PHASE}")
    a(f"load {PHASE}")
    a("push 120")
    a("lt")
    a("jz swap")
    a("jmp paint")
    # ---- two seconds up: become the next program -----------------------
    a("swap:")
    a("push 0")
    a(f"store {PHASE}")
    a(f"push {BANK_AT + nxt * BANK_STRIDE}")
    a(f"store {spec.OVL_SRC}")
    a("push 0")
    a(f"store {spec.OVL_DST}")
    a(f"push {BANK_STRIDE}")
    a(f"store {spec.OVL_LEN}")
    a("push 1")
    a(f"store {spec.OVL_GO}")
    # ---- paint: this program's own colour and its own count of bars ----
    a("paint:")
    a(f"push {bars}")
    a(f"store {DL}")
    for k in range(bars):
        base = DL + 1 + k * spec.DL_STRIDE
        x0 = 20 + k * 42
        for i, v in enumerate((x0, 60, x0 + 30, 60, x0, 220)):
            a(f"push {v}")
            a(f"store {base + i}")
        a(f"push {colour}")
        a(f"store {base + 6}")
    a("halt")
    return L


def assemble_bank(lines):
    """Hand-assemble one program to words, so it can ride in CRAM."""
    labels, prog = {}, []
    for ln in lines:
        if ln.endswith(":"):
            labels[ln[:-1]] = len(prog)
        else:
            prog.append(ln)
    out = []
    for ln in prog:
        tok = ln.split()
        code, has_imm = spec.OPS[tok[0]]
        imm = 0
        if has_imm:
            t = tok[1]
            imm = labels[t] if t in labels else int(t, 0)
        out.append((code << 24) | (imm & 0xFFFFFF))
    return out


def build():
    L = []
    a = L.append
    a("; overlay.zol -- GENERATED by gen_overlay.py, do not edit")
    a("; three programs, one IMEM: the cart is no longer 4,096 words")
    a("")
    banks = [assemble_bank(program(i)) for i in range(len(STYLES))]
    for i, b in enumerate(banks):
        assert len(b) <= BANK_STRIDE, f"program {i} is {len(b)} words"
        for off in range(0, len(b), 12):
            chunk = " ".join(str(v) for v in b[off:off + 12])
            a(f".cram {BANK_AT + i * BANK_STRIDE + off} {chunk}")
    a("")
    # the resident program IS program one, so the very first frame paints
    L.extend(program(0))
    return L, banks


if __name__ == "__main__":
    lines, banks = build()
    out = HERE / "overlay.zol"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out.name}: {len(banks)} programs of "
          f"{[len(b) for b in banks]} words, one resident at a time")
