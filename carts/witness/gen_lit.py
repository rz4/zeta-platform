#!/usr/bin/env python3
"""gen_lit.py -- writes carts/witness/lit.zol: OBJ_OTINT's witness.

Four objects, one mesh, one difference between them: where their light
comes from.

  ground   no flag           -- the unlit path, unchanged, and the proof
                               of that is the cross gate
  cube A   OBJ_OTINT, red    -- an UNTEXTURED face modulated, which
                               OBJ_TINT has never been able to do
  cube B   no OBJ_OTINT      -- the same mesh, same colours, unlit: the
                               reference that makes A's difference read
                               as light rather than as new geometry
  cube C   OBJ_OTINT, live   -- its tint recomputed EVERY FRAME by the
                               program, from one word

C is the whole point. Before this flag an actor's light lived in nf
colour words inside its mesh, so re-lighting it per frame meant
rewriting the mesh -- which is why every actor in this tree is lit for
exactly one condition. C is lit by a single store.

Run me after changing anything: python3 carts/witness/gen_lit.py
"""
import sys
from pathlib import Path

ROOT = next(p for p in Path(__file__).resolve().parents
            if (p / "zeta" / "spec.py").is_file())
sys.path.insert(0, str(ROOT))
from zeta import carts as _carts                         # noqa: E402
_carts.on_path()                 # sibling generators, wherever they live
from zeta import spec                          # noqa: E402
from gen_cube import cube_mesh, data_lines, ground_mesh   # noqa: E402

ONE = 65536
GROUND_AT, CUBE_AT = 512, 1400


def tint(r, g, b):
    """The 15 bits of 5:5:5 light that live in the object's flags word."""
    return (r << 27) | (g << 22) | (b << 17)


def word(v):
    """A flags word with bit 31 set is 2^31 or more, and DMEM is signed."""
    return v - (1 << 32) if v >= (1 << 31) else v


CULL = spec.OBJ_CULL
OTINT = spec.OBJ_OTINT

# object 3's flags cell -- derived, never hardcoded: gen_cube.py shipped a
# cube that could not rotate for three amendments because these were
# typed in once and OL_BASE moved underneath them.
_OBJ3 = spec.OL_BASE + 1 + 3 * spec.OL_STRIDE
OBJ3_FLAGS = _OBJ3 + 5

PROGRAM = """
; ---- cube C is re-lit every frame, by one store ------------------------
; T counts; T & 31 ramps the light 0..31 and wraps -- a NEW light
; every frame, which is the property no mesh-baked tint has.
; The mesh is never touched -- this is the difference the flag exists
; to make.
load T
push 1
add
store T

load T
push 31
and                        ; the live channel, 0..31
dup
shl 22                     ; green
swap
shl 27                     ; ...and red with it, so it reads as WARMTH
                           ; rather than as one channel sliding
or
push {LIT}                 ; OBJ_CULL | OBJ_OTINT
or
store {OBJ3_FLAGS}
halt
"""


def main():
    g_verts, g_faces = ground_mesh(10, 1)
    c_verts, c_faces = cube_mesh()
    g_lines, g_len = data_lines(GROUND_AT, g_verts, g_faces)
    c_lines, c_len = data_lines(CUBE_AT, c_verts, c_faces)
    assert GROUND_AT + g_len <= CUBE_AT and CUBE_AT + c_len <= spec.DL_BASE

    objs = [
        # mesh       x           y  z          yaw  flags
        (GROUND_AT,  0,          0, 0,         0,   CULL),
        (CUBE_AT,   -2 * ONE,    0, 2 * ONE,   0,   CULL | OTINT
         | tint(31, 6, 6)),                       # A: lit red
        (CUBE_AT,    0,          0, 2 * ONE,   0,   CULL),
        (CUBE_AT,    2 * ONE,    0, 2 * ONE,   0,   CULL | OTINT
         | tint(0, 0, 0)),                        # C: the program's
    ]
    ol = " ".join(str(v) for o in objs for v in
                  (o[0], o[1], o[2], o[3], o[4], word(o[5])))

    out = ["; lit.zol -- OBJ_OTINT's witness. GENERATED by carts/witness/gen_lit.py",
           "; -- edit that, not this.",
           ";",
           "; Left cube: lit red by its OBJECT word. Middle: the same mesh,",
           "; unlit, so the difference reads as light. Right: re-lit every",
           "; frame by the program, without touching a single mesh word.",
           "",
           ".const T 16",
           "",
           ".data 8 0 91750 -262144 0   ; camera: x 0, y 1.4, z -4, yaw 0",
           f".data {spec.AU_BASE + 4} 38448 6",
           "",
           f"; object list: {len(objs)} objects",
           f".data {spec.OL_BASE} {len(objs)} {ol}",
           "",
           f"; ---- ground mesh: {g_len} words ----"]
    out += g_lines
    out += ["", f"; ---- cube mesh: {c_len} words ----"]
    out += c_lines
    out.append(PROGRAM.format(OBJ3_FLAGS=OBJ3_FLAGS, LIT=CULL | OTINT))
    path = Path(__file__).parent / "lit.zol"
    path.write_text("\n".join(out))
    print(f"wrote {path}: {len(objs)} objects, ground {g_len}w, cube {c_len}w")


if __name__ == "__main__":
    main()
