#!/usr/bin/env python3
"""gen_glow.py -- writes carts/witness/glow.zol: BLEND_ADD's witness.

Two blended quads over the same checkered floor, identical in every
respect -- same mesh, same colour, same alpha, same depth -- except
their blend MODE.

  left   BLEND_LERP  dst*(16-a) + src*a   -- what blending has meant here
  right  BLEND_ADD   dst + src*a          -- saturated at 31

The floor is in THREE tones on purpose. Over the BLACK tiles the two
modes agree exactly, and that is not a weakness of the demo -- with
dst = 0 the two formulas ARE the same arithmetic. Over the WHITE tiles
the lerp pulls white DOWN toward the quad's colour while the additive
can only push it up, into saturation. And over the MID-GREY, the
additive lands brighter than the floor AND brighter than the quad, which
no lerp of two colours can ever produce.

That is the one thing a lerp cannot fake. A lerp moves a pixel TOWARD
the source colour: it can darken a bright pixel and it can never
brighten one. It is the reason a glow composited with a lerp reads as a
sticker over the picture rather than as light coming off something.

The arithmetic makes the invariant exact rather than approximate:
add - lerp = dst*a, which is never negative. Additive is >= lerp at
every pixel, with equality only where dst = 0 -- and the suite gates on
that, not on a screenshot.

Run me after changing anything: python3 carts/witness/gen_glow.py
"""
import sys
from pathlib import Path

ROOT = next(p for p in Path(__file__).resolve().parents
            if (p / "zeta" / "spec.py").is_file())
sys.path.insert(0, str(ROOT))
from zeta import carts as _carts                         # noqa: E402
_carts.on_path()                 # sibling generators, wherever they live
from zeta import spec                          # noqa: E402
from gen_cube import data_lines               # noqa: E402

ONE = 65536
GROUND_AT, QUAD_AT = 512, 1400

GLOW = 0xFF8020          # a warm bright source: r5 31, g5 16, b5 4
ALPHA = 8                # half


def ground_mesh(n=10, tile=1):
    """A floor in THREE tones, not two. A black/white checker cannot show
    what additive blending is for: where dst = 0 the lerp and the add are
    the same arithmetic, and where dst = 31 both saturate. The property
    only becomes visible over MID-TONES, where the additive lands
    brighter than the destination AND brighter than the source, which no
    lerp of the two can ever do."""
    verts, faces = [], []
    h = n // 2
    tones = (0x000000, 0x808080, 0xFFFFFF)   # nigredo, albedo, and between
    for j in range(n + 1):
        for i in range(n + 1):
            verts += [(i - h) * ONE * tile, 0, (j - h) * ONE * tile]
    for j in range(n):
        for i in range(n):
            a = j * (n + 1) + i
            b, c, d = a + 1, a + 1 + (n + 1), a + (n + 1)
            col = tones[(i + j) % 3]
            faces += [(a, c, b, col), (a, d, c, col)]
    return verts, faces


def face_word(rgb, alpha, mode):
    """The face colour word: colour 23:0, alpha 28:24, MODE 30:29."""
    return (rgb | (alpha << spec.BLEND_A_SHIFT)
            | (mode << spec.BLEND_MODE_SHIFT))


def quad_mesh(w=2, h=2):
    """One upright quad, w x h units, centred on its own origin."""
    hw, hh = (w * ONE) // 2, h * ONE
    verts = [-hw, 0, 0,  hw, 0, 0,  hw, hh, 0,  -hw, hh, 0]
    return verts, [(0, 2, 1), (0, 3, 2)]


def quad_data(base, mode):
    verts, tris = quad_mesh()
    faces = [(a, b, c, face_word(GLOW, ALPHA, mode)) for a, b, c in tris]
    return data_lines(base, verts, faces)


def main():
    g_verts, g_faces = ground_mesh(10, 1)
    g_lines, g_len = data_lines(GROUND_AT, g_verts, g_faces)
    l_lines, l_len = quad_data(QUAD_AT, spec.BLEND_LERP)
    a_at = QUAD_AT + l_len
    a_lines, a_len = quad_data(a_at, spec.BLEND_ADD)
    assert GROUND_AT + g_len <= QUAD_AT and a_at + a_len <= spec.DL_BASE

    # THE BLEND-ORDER LAW (spec.py): all opaque geometry BEFORE any
    # blended geometry. The ground is object 0 for that reason, not by
    # accident -- submitted after the quads it would paint over them.
    objs = [
        (GROUND_AT, 0, 0, 0, 0, spec.OBJ_CULL),
        (QUAD_AT, -int(1.6 * ONE), 0, int(1.0 * ONE), 0, spec.OBJ_BLEND),
        (a_at,     int(1.6 * ONE), 0, int(1.0 * ONE), 0, spec.OBJ_BLEND),
    ]
    ol = " ".join(str(v) for o in objs for v in o)

    out = ["; glow.zol -- BLEND_ADD's witness. GENERATED by carts/witness/gen_glow.py",
           "; -- edit that, not this.",
           ";",
           "; Two identical blended quads: LEFT lerps, RIGHT adds. Over the",
           "; black tiles they agree -- with dst = 0 the two formulas are the",
           "; same arithmetic. Over the WHITE the lerp pulls white DOWN toward",
           "; the quad's colour while the additive can only push it up into",
           "; saturation. Over the MID-GREY the additive lands brighter than",
           "; the floor AND brighter than the quad, which no lerp can do.",
           "",
           ".data 8 0 91750 -262144 0   ; camera: x 0, y 1.4, z -4, yaw 0",
           f".data {spec.AU_BASE + 4} 38448 6",
           "",
           f"; object list: {len(objs)} objects, opaque first",
           f".data {spec.OL_BASE} {len(objs)} {ol}",
           "",
           f"; ---- ground mesh: {g_len} words ----"]
    out += g_lines
    out += ["", f"; ---- LERP quad: {l_len} words ----"] + l_lines
    out += ["", f"; ---- ADD quad: {a_len} words ----"] + a_lines
    out += ["", "halt"]
    path = Path(__file__).parent / "glow.zol"
    path.write_text("\n".join(out))
    print(f"wrote {path}: ground {g_len}w, quads {l_len}w + {a_len}w")


if __name__ == "__main__":
    main()
