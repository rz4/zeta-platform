#!/usr/bin/env python3
"""gen_gaze.py -- writes carts/witness/gaze.zol: spec.GAZE_BASE's witness.

EIGHT PIXELS, ANSWERED AT THE FLUSH. The machine names, for each pixel
the cart lists, who owns it and how deep it stands when the frame is
finished. This cart is seen.zol's scene -- a ground, a subject, an
occluder sweeping across it, a marker -- with eight watched pixels laid
across it in scan order: sky, the subject's top, a row straight through
the occluder's path, the ground near and far.

HOW IT WITNESSES ITSELF, which is seen.zol's way and for its reason: an
answer is a number in DMEM, and `cross` compares pictures. So the eight
answers are xored and folded onto their own low bits, and the marker
cube stands where the fold puts it. One owner or one depth count wrong,
on any of the eight, and the marker is somewhere else.

    acc = ANS[0] xor ANS[1] xor ... xor ANS[7]
    h   = acc xor acc>>4 xor acc>>8 xor acc>>12 xor acc>>16 xor acc>>20
    the marker stands at x = (h&7) - 3, z = ((h>>3)&7) + 3

THE LIST'S OWN LAW IS WITNESSED TOO. On every eighth frame the cart
writes the list with its fifth entry moved BEFORE its fourth. The law
says the list ends there: entries five to eight answer -1. A machine
that answered them anyway would fold a different number.

Run me after changing anything: python3 carts/witness/gen_gaze.py
"""
import sys
from pathlib import Path

ROOT = next(p for p in Path(__file__).resolve().parents
            if (p / "zeta" / "spec.py").is_file())
sys.path.insert(0, str(ROOT))
from zeta import carts as _carts                         # noqa: E402
_carts.on_path()                 # sibling generators, wherever they live
from zeta import spec                          # noqa: E402
from gen_cube import cube_mesh, data_lines, ground_mesh   # noqa: E402

ONE = 65536
GROUND_AT, CUBE_AT = 512, 1400
P, ACC, H = 16, 17, 18                         # scratch
GOOD, BAD = 19, 20      # the fifth entry's two words: a push carries 24
                        # bits and (y << 16) | x wants 25, so they are data

_OBJ = [spec.OL_BASE + 1 + k * spec.OL_STRIDE for k in range(4)]
_X, _Z = 1, 3                                  # field offsets in a record
G, A = spec.GAZE_BASE, spec.GAZE_ANS

# the watched pixels, (x, y), in scan order: y rising, then x
WATCHED = [(160, 20),              # sky: the room, the far depth
           (160, 158),             # where the marker often stands
           (60, 180), (120, 180),  # a row through the occluder's sweep,
           (160, 180), (200, 180), # the subject standing in its middle
           (160, 205),             # the subject's foot / the occluder's
           (160, 270)]             # the ground, near: the LAST band, which
                                   # leaves by its own flush and no clear
assert len(WATCHED) == spec.GAZE_MAX
assert all(b[1] * spec.W + b[0] > a[1] * spec.W + a[0]
           for a, b in zip(WATCHED, WATCHED[1:]))
WORDS = [(y << 16) | x for x, y in WATCHED]
# ...and the same list with entry 4 put BEFORE entry 3: it must end there
BROKEN = WORDS[:4] + [(180 << 16) | 100] + WORDS[5:]

_fold = "\n".join(f"load {A + i}\nxor" for i in range(1, spec.GAZE_MAX))

PROGRAM = f"""
; ---- the sweep: the occluder crossing the subject, whole ------------
load {P}
push 8
add
push 255
and
store {P}

load {P}
push 128
sub
shl 9
store {_OBJ[2] + _X}

; ---- the list: good on seven frames of eight, out of order on one ---
load {BAD}
store {G + 5}
load {P}
push 56
and
jz disordered
load {GOOD}
store {G + 5}
disordered:

; ---- the fold (spec.GAZE_ANS) ---------------------------------------
load {A}
{_fold}
store {ACC}

load {ACC}
load {ACC}
shr 4
xor
load {ACC}
shr 8
xor
load {ACC}
shr 12
xor
load {ACC}
shr 16
xor
load {ACC}
shr 20
xor
store {H}

; ---- the marker stands where the answers put it ---------------------
load {H}
push 7
and
shl 16
push 196608
sub
store {_OBJ[3] + _X}

load {H}
shr 3
push 7
and
shl 16
push 262144
add
store {_OBJ[3] + _Z}
halt
"""


def main():
    g_verts, g_faces = ground_mesh(10, 1)
    c_verts, c_faces = cube_mesh()
    g_lines, g_len = data_lines(GROUND_AT, g_verts, g_faces)
    c_lines, c_len = data_lines(CUBE_AT, c_verts, c_faces)
    assert GROUND_AT + g_len <= CUBE_AT and CUBE_AT + c_len <= spec.DL_BASE

    objs = [
        (GROUND_AT, 0, 0, 0, 0, spec.OBJ_CULL),
        (CUBE_AT, 0, 0, int(3.2 * ONE), 0, spec.OBJ_CULL),
        (CUBE_AT, 0, 0, int(1.15 * ONE), 0, spec.OBJ_CULL | spec.OBJ_EDGE),
        (CUBE_AT, 0, 0, int(4.0 * ONE), 0, spec.OBJ_CULL | spec.OBJ_EDGE),
    ]
    ol = " ".join(str(v) for o in objs for v in o)

    out = ["; gaze.zol -- spec.GAZE_BASE's witness. GENERATED by",
           "; carts/witness/gen_gaze.py -- edit that, not this.",
           ";",
           "; The marker cube stands where the eight watched pixels' owners",
           "; and depths put it. One of them wrong, in any bit, and it lands",
           "; somewhere else.",
           "",
           ".data 8 0 91750 -262144 0    ; camera: x 0, y 1.4, z -4",
           f".data {spec.EDGE_RGB} 16316096   ; 0xF8F8C0",
           f".data {spec.AU_BASE + 4} 38448 6",
           "",
           f"; the gaze: {spec.GAZE_MAX} pixels, (y << 16) | x, in scan order",
           f".data {G} {spec.GAZE_MAX} " + " ".join(str(w) for w in WORDS),
           f".data {GOOD} {WORDS[4]} {BROKEN[4]}",
           "",
           f"; object list: {len(objs)} objects",
           f".data {spec.OL_BASE} {len(objs)} {ol}",
           "",
           f"; ---- ground mesh: {g_len} words ----"]
    out += g_lines
    out += ["", f"; ---- cube mesh: {c_len} words ----"] + c_lines
    out.append(PROGRAM)
    path = Path(__file__).parent / "gaze.zol"
    path.write_text("\n".join(out))
    print(f"wrote {path}: {len(objs)} objects, {spec.GAZE_MAX} watched pixels")


if __name__ == "__main__":
    main()
