#!/usr/bin/env python3
"""gen_voice.py -- writes carts/witness/voice.zol: the wavetable voice's demo.

The field law, made audible. The rasterizer walks a bounded table at
43.2 MHz and calls the result a texture; this walks a bounded table at
48 kHz and calls it a voice. Same accumulator, same window, one
primitive -- so the cart that proves it lets you HEAR the table while
you watch that same table drawn in front of you.

Four channels, all in wave mode (spec.AU_WAVE), tuned to open fifths on
A = 432 -- the clock's own tuning, since 43.2 MHz is exactly 100,000
cycles per 432 Hz period. The face buttons swap the page:

    A  sine      the pure tone: nothing but the fundamental
    B  saw       every harmonic falling as 1/n -- the bright one
    X  square    odd harmonics only: hollow, clarinet-ish
    Y  bell      fundamental + 3rd + 7th partials at unequal weights,
                 which is the point -- no pulse or triangle channel of
                 the era could make this shape at all

Dpad: up/down transposes an octave, left/right sets the volume.

The screen draws the live page as 64 columns of citrinitas over the
green zero line. What you hear is what you see: the same numbers.
"""
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = next(p for p in Path(__file__).resolve().parents
            if (p / "zeta" / "spec.py").is_file())
sys.path.insert(0, str(ROOT))
from zeta import carts as _carts                         # noqa: E402
_carts.on_path()                 # sibling generators, wherever they live

from zeta import spec                                    # noqa: E402

WAVE_AT = 900                  # the live page: WAV_WORDS packed words
BANK_AT = 1000                 # 4 banks x WAV_WORDS, packed (for the ear)
VIEW_AT = 1400                 # 4 banks x WAV_W, one per word (for the eye)
SEL, OCT, VOL, I, X0, X1, YV, LOCK = 16, 17, 18, 19, 20, 21, 22, 23
CYCLE = 32                     # frames per shape while unattended

DL = spec.DL_BASE
COLS = 64                      # columns drawn (every 4th sample)
ZERO_Y = 150                   # the zero line
C_WAVE = 0xE6C010              # citrinitas
CHORD = [216.0, 324.0, 432.0, 648.0]


def inc(f):
    return int(round(f * (1 << 24) / spec.SND_HZ))


def waves():
    n = spec.WAV_W
    sine = [int(round(127 * math.sin(2 * math.pi * i / n))) for i in range(n)]
    saw = [((i * 256) // n) - 128 for i in range(n)]
    square = [127 if i < n // 2 else -127 for i in range(n)]
    bell = []
    for i in range(n):
        t = 2 * math.pi * i / n
        v = (1.00 * math.sin(t) + 0.55 * math.sin(3 * t)
             + 0.30 * math.sin(7 * t))
        bell.append(max(-128, min(127, int(round(v * 127 / 1.85)))))
    return [sine, saw, square, bell]


def pack(samples):
    out = []
    for w in range(spec.WAV_WORDS):
        v = 0
        for b in range(4):
            v |= (samples[w * 4 + b] & 0xFF) << (8 * b)
        out.append(v)
    return out


def data_rows(addr, values, per=16):
    rows = []
    for off in range(0, len(values), per):
        rows.append(f".data {addr + off} "
                    + " ".join(str(v) for v in values[off:off + per]))
    return rows


def build():
    L = []
    a = L.append
    a("; voice.zol -- GENERATED by gen_voice.py, do not edit")
    a("; the sampled field at 48 kHz -- the same walk as a texture")
    a("")
    for name, v in (("SEL", SEL), ("OCT", OCT), ("VOL", VOL), ("I", I),
                    ("X0", X0), ("X1", X1), ("YV", YV),
                    ("LOCK", LOCK), ("PAD", spec.REG_PAD)):
        a(f".const {name} {v}")
    a("")
    a(f".data {SEL} 0 0 9 0 0 0 0 0")
    a(f".data {spec.WAV_SRC} {WAVE_AT}")
    for k, w in enumerate(waves()):
        L.extend(data_rows(BANK_AT + k * spec.WAV_WORDS, pack(w)))
        L.extend(data_rows(VIEW_AT + k * spec.WAV_W, w))
    a("")

    # ---- unattended, it walks its own shapes; a button takes the wheel --
    a("load LOCK"); a("jz auto"); a("jmp manual")
    a("auto:")
    a(f"load {spec.REG_FRAME}"); a("shr 5")      # one shape every 32
    a("push 3"); a("and"); a("store SEL")        # frames, all four in turn
    a("manual:")
    for bit, tag, k in ((spec.PAD_A, "a", 0), (spec.PAD_B, "b", 1),
                        (spec.PAD_X, "x", 2), (spec.PAD_Y, "y", 3)):
        a("load PAD"); a(f"push {bit}"); a("and"); a(f"jz no_{tag}")
        a(f"push {k}"); a("store SEL"); a("push 1"); a("store LOCK")
        a(f"no_{tag}:")
    for bit, tag, cell, val in ((spec.PAD_UP, "up", "OCT", 1),
                                (spec.PAD_DOWN, "dn", "OCT", 0),
                                (spec.PAD_RIGHT, "rt", "VOL", 15),
                                (spec.PAD_LEFT, "lf", "VOL", 4)):
        a("load PAD"); a(f"push {bit}"); a("and"); a(f"jz no_{tag}")
        a(f"push {val}"); a(f"store {cell}")
        a(f"no_{tag}:")

    # ---- copy the chosen bank into the live page ------------------------
    a("push 0"); a("store I")
    a("copy:")
    a("load SEL"); a(f"push {spec.WAV_WORDS}"); a("mul")
    a(f"push {BANK_AT}"); a("add"); a("load I"); a("add"); a("loadi")
    a("load I"); a(f"push {WAVE_AT}"); a("add"); a("storei")
    a("load I"); a("push 1"); a("add"); a("dup"); a("store I")
    a(f"push {spec.WAV_WORDS}"); a("lt"); a("jz voices"); a("jmp copy")

    # ---- four voices, all walking the page ------------------------------
    a("voices:")
    for c, f in enumerate(CHORD):
        a("load OCT"); a(f"jz lo{c}")
        a(f"push {inc(f) * 2}"); a(f"jmp put{c}")
        a(f"lo{c}:"); a(f"push {inc(f)}")
        a(f"put{c}:"); a(f"store {spec.AU_BASE + 2 * c}")
        a("load VOL"); a(f"push {spec.AU_WAVE}"); a("or")
        a(f"store {spec.AU_BASE + 2 * c + 1}")

    # ---- draw the live page: one triangle per column --------------------
    a(f"push {COLS}"); a(f"store {DL}")
    a("push 0"); a("store I")
    a("trace:")
    a("load I"); a("push 4"); a("mul"); a("push 32"); a("add")
    a("dup"); a("store X0"); a("push 3"); a("add"); a("store X1")
    a("load SEL"); a(f"push {spec.WAV_W}"); a("mul")
    a(f"push {VIEW_AT}"); a("add")
    a("load I"); a("push 4"); a("mul"); a("add"); a("loadi")
    a("shr 1"); a(f"push {ZERO_Y}"); a("swap"); a("sub"); a("store YV")
    # the triangle: (x0, zero) (x1, zero) (x0, y)
    for k, expr in enumerate((["load X0"], [f"push {ZERO_Y}"],
                              ["load X1"], [f"push {ZERO_Y}"],
                              ["load X0"], ["load YV"],
                              [f"push {C_WAVE}"])):
        L.extend(expr)
        a("load I"); a("push 7"); a("mul")
        a(f"push {DL + 1 + k}"); a("add"); a("storei")
    a("load I"); a("push 1"); a("add"); a("dup"); a("store I")
    a(f"push {COLS}"); a("lt"); a("jz done"); a("jmp trace")
    a("done:")
    a("halt")
    return L


if __name__ == "__main__":
    out = HERE / "voice.zol"
    out.write_text("\n".join(build()) + "\n")
    n = sum(1 for ln in build() if ln and not ln.startswith((";", ".")))
    print(f"wrote {out.name}: {n} instructions")
