#!/usr/bin/env python3
"""gen_seen.py -- writes carts/seen.zol: spec.VIS_BASE's witness.

THE PANEL IS A SENSOR. The rasterizer visits every visible point of every
surface and throws all of it away but the colour. This cart proves the
first of it kept: how many pixels of each object the panel ACTUALLY
SHOWED -- counted off the identity plane at flush time, so an object
drawn over afterwards does not count.

HOW IT WITNESSES ITSELF. A count is a number in DMEM, and `cross`
compares framebuffers and sample streams, never DMEM -- so the cart has
to spend the number on something the panel shows. It does:

    acc = VIS[0] xor VIS[1] xor VIS[2] xor VIS[3]
    h   = acc xor acc>>4 xor acc>>8 xor acc>>12 xor acc>>16
    the marker cube stands at x = (h&7) - 3, z = ((h>>3)&7) + 3

The fold puts EVERY bit of every count into the low six, and the low six
move the marker a whole world unit a step. So a one-pixel disagreement
between the law and the silicon -- on any object, in any bit -- throws
the marker somewhere else entirely, and the pictures stop matching.

The marker's own count feeds the next frame's fold, one frame late,
which makes the whole thing a deliberate amplifier: agreement is stable,
and disagreement runs away. That is what a witness is for. It does not
make a pretty demo, and it is not meant to be one.

An occluder sweeps across the subject cube so the counts are never
still. Measured over the gate's forty frames the subject falls from
1,514 pixels to 184 and climbs back -- an eight-fold swing, which
exercises the accumulator's carries rather than one lucky number, and
which is itself the claim: a count that did not track the occluder is
not a count of what the panel showed.

Run me after changing anything: python3 carts/gen_seen.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from zeta import spec                          # noqa: E402
from gen_cube import cube_mesh, data_lines, ground_mesh   # noqa: E402

ONE = 65536
GROUND_AT, CUBE_AT = 512, 1400
P, ACC, H = 16, 17, 18                         # scratch

_OBJ = [spec.OL_BASE + 1 + k * spec.OL_STRIDE for k in range(4)]
_X, _Z = 1, 3                                  # field offsets in a record
V = spec.VIS_BASE

PROGRAM = f"""
; ---- the sweep: the occluder crossing the subject, whole ------------
; EIGHT a frame, not one: the gate watches 40 frames and the crossing
; has to finish inside them, or the claim is checked against a corner of
; the range instead of the range
load {P}
push 8
add
push 255
and
store {P}

; occluder x = (phase - 128) * 512, i.e. -1.0 .. +1.0 world units
load {P}
push 128
sub
shl 9
store {_OBJ[2] + _X}

; ---- the fold (spec.VIS_BASE) ---------------------------------------
; every object's count, xored together, then folded onto itself in
; nibbles so that no bit of any count can go unwitnessed
load {V + 0}
load {V + 1}
xor
load {V + 2}
xor
load {V + 3}
xor
store {ACC}

load {ACC}
load {ACC}
shr 4
xor
load {ACC}
shr 8
xor
load {ACC}
shr 12
xor
load {ACC}
shr 16
xor
store {H}

; ---- the marker stands where the counts put it ----------------------
load {H}
push 7
and
shl 16
push 196608
sub
store {_OBJ[3] + _X}

load {H}
shr 3
push 7
and
shl 16
push 262144
add
store {_OBJ[3] + _Z}
halt
"""


def main():
    g_verts, g_faces = ground_mesh(10, 1)
    c_verts, c_faces = cube_mesh()
    g_lines, g_len = data_lines(GROUND_AT, g_verts, g_faces)
    c_lines, c_len = data_lines(CUBE_AT, c_verts, c_faces)
    assert GROUND_AT + g_len <= CUBE_AT and CUBE_AT + c_len <= spec.DL_BASE

    objs = [
        # 0: the ground. A big count, so the fold's HIGH bits get used
        (GROUND_AT, 0, 0, 0, 0, spec.OBJ_CULL),
        # 1: the subject, standing still and being hidden
        (CUBE_AT, 0, 0, int(3.2 * ONE), 0, spec.OBJ_CULL),
        # 2: the occluder, sweeping. CLOSE, so that mid-crossing it
        #    hides the subject entirely and the count reaches zero
        (CUBE_AT, 0, 0, int(1.15 * ONE), 0, spec.OBJ_CULL | spec.OBJ_EDGE),
        # 3: the marker, standing where the counts put it
        (CUBE_AT, 0, 0, int(4.0 * ONE), 0, spec.OBJ_CULL | spec.OBJ_EDGE),
    ]
    ol = " ".join(str(v) for o in objs for v in o)

    out = ["; seen.zol -- spec.VIS_BASE's witness. GENERATED by",
           "; carts/gen_seen.py -- edit that, not this.",
           ";",
           "; The marker cube stands where the frame's visible-pixel counts",
           "; put it. Both machines count off their own identity plane; if",
           "; either is off by a pixel the marker lands somewhere else.",
           "",
           ".data 8 0 91750 -262144 0    ; camera: x 0, y 1.4, z -4",
           f".data {spec.EDGE_RGB} 16316096   ; 0xF8F8C0",
           f".data {spec.AU_BASE + 4} 38448 6",
           "",
           f"; object list: {len(objs)} objects",
           f".data {spec.OL_BASE} {len(objs)} {ol}",
           "",
           f"; ---- ground mesh: {g_len} words ----"]
    out += g_lines
    out += ["", f"; ---- cube mesh: {c_len} words ----"] + c_lines
    out.append(PROGRAM)
    path = Path(__file__).parent / "seen.zol"
    path.write_text("\n".join(out))
    print(f"wrote {path}: {len(objs)} objects, ground {g_len}w, cube {c_len}w")


if __name__ == "__main__":
    main()
