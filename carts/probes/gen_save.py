#!/usr/bin/env python3
"""gen_save.py -- writes carts/probes/save.zol: the machine remembers.

It counts how many times it has been switched on. Read the counter off
the card, write it back one higher, and show it.

  the BAND across the top    what is happening right now
      RED      the card gave us zero: first ever run, or nothing saved
      GREEN    the card gave us a number -- it remembered
      YELLOW   a transfer is in flight

  the ROW of cells below     the counter itself, in binary, high bit left

Power the machine off and on. The cells should read one higher every
time, which is the whole of what a save is. The earlier version drew the
count as a bar 12 px per run, which at a count of one is a sliver next
to a full-width band -- unreadable, and my instructions for it were
worse. Cells cannot be misread.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = next(p for p in Path(__file__).resolve().parents
            if (p / "zeta" / "spec.py").is_file())
sys.path.insert(0, str(ROOT))
from zeta import carts as _carts                         # noqa: E402
_carts.on_path()                 # sibling generators, wherever they live

from zeta import spec                                    # noqa: E402

DL = spec.DL_BASE
V, W, C, T = 700, 701, 16, 17
NBITS = 8
CELL_W, CELL_H, GAP = 30, 60, 6
X0, Y0 = 24, 120
C_ONE, C_ZERO = 0xEEEEEE, 0x2A2A33


def build():
    L = []
    a = L.append
    a("; save.zol -- GENERATED by gen_save.py, do not edit")
    a("; the machine counts how many times it has been switched on")
    a("")
    a(".sd 2 0 0")
    for n, v in (("GO", spec.SD_GO), ("SLOTC", spec.SD_SLOT),
                 ("OFFC", spec.SD_OFF), ("DSTC", spec.SD_DST),
                 ("LENC", spec.SD_LEN), ("FRAME", spec.REG_FRAME),
                 ("V", V), ("W", W), ("C", C), ("T", T)):
        a(f".const {n} {v}")
    a("")
    # ---- frame 60: read the counter -------------------------------------
    # NOT frame 1. The probe reads at 60 and works; this read at frame 1
    # came back zero every time, so something on the card side is not
    # ready a sixtieth of a second after the console starts.
    a("load FRAME")
    a("push 60")
    a("eq")
    a("jz try_save")
    a("push 2")
    a("store SLOTC")
    a("push 0")
    a("store OFFC")
    a("push V")
    a("store DSTC")
    a("push 1")
    a("store LENC")
    a(f"push {spec.SD_READ}")
    a("store GO")
    a("jmp draw")
    # ---- frame 8 and every 128: write it back, one higher ---------------
    a("try_save:")
    a("load FRAME")
    a("push 127")
    a("and")
    a("push 100")               # ...and save well after the read landed
    a("eq")
    a("jz draw")
    a("load V")
    a("push 1")
    a("add")
    a("store W")
    a("push 2")
    a("store SLOTC")
    a("push 0")
    a("store OFFC")
    a("push W")
    a("store DSTC")
    a("push 1")
    a("store LENC")
    a(f"push {spec.SD_SAVE}")
    a("store GO")
    # ---- the band --------------------------------------------------------
    a("draw:")
    a("load GO")
    a("jz settled")
    a("push 0xE6C010")
    a("store C")
    a("jmp rows")
    a("settled:")
    a("load V")
    a("jz nothing")
    a("push 0x20B040")
    a("store C")
    a("jmp rows")
    a("nothing:")
    a("push 0xC42020")
    a("store C")
    a("rows:")
    a(f"push {2 + NBITS * 2}")
    a(f"store {DL}")
    tri = 0

    def quad(x0, y0, x1, y1, colour_ops):
        nonlocal tri
        for (px0, py0, px1, py1, px2, py2) in (
                (x0, y0, x1, y0, x0, y1), (x1, y0, x1, y1, x0, y1)):
            base = DL + 1 + tri * spec.DL_STRIDE
            for k, val in enumerate((px0, py0, px1, py1, px2, py2)):
                a(f"push {val}")
                a(f"store {base + k}")
            L.extend(colour_ops)
            a(f"store {base + 6}")
            tri += 1

    quad(0, 0, 320, 60, ["load C"])
    for bit in range(NBITS):
        a("load V")
        a(f"shr {bit}")
        a("push 1")
        a("and")
        a(f"jz z{bit}")
        a(f"push {C_ONE}")
        a(f"jmp c{bit}")
        a(f"z{bit}:")
        a(f"push {C_ZERO}")
        a(f"c{bit}:")
        a("store T")
        x = X0 + (NBITS - 1 - bit) * (CELL_W + GAP)
        quad(x, Y0, x + CELL_W, Y0 + CELL_H, ["load T"])
    a("halt")
    return L


if __name__ == "__main__":
    out = HERE / "save.zol"
    lines = build()
    out.write_text("\n".join(lines) + "\n")
    n = sum(1 for ln in lines if ln and not ln.startswith((";", ".")))
    print(f"wrote {out.name}: {n} instructions, band + {NBITS} cells")
