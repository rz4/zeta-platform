#!/usr/bin/env python3
"""gen_card.py -- writes carts/probes/card.zol: the card's demo and its gate.

Content that was never in the cart. The .sd section here is NOT part of
the .zbin the console boots with -- it is a separate file on the SD, and
the machine pulls it in a chunk at a time while the game runs.

The cart asks for sixteen words, waits (spec.SD_LATENCY frames, always,
whatever the card actually did), draws them as a row of bars, and then
asks for the next sixteen -- walking a 256-word image forever. So the
picture is a live readout of a transfer in flight: the bars step to their
new shape exactly on the frame the law says the data may be seen, and the
cross holds both machines to that same frame.

The image is a sine table, so a correct machine draws a smooth travelling
wave and a machine that lands data early, late, or short draws a visibly
broken one.
"""
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = next(p for p in Path(__file__).resolve().parents
            if (p / "zeta" / "spec.py").is_file())
sys.path.insert(0, str(ROOT))
from zeta import carts as _carts                         # noqa: E402
_carts.on_path()                 # sibling generators, wherever they live

from zeta import spec                                    # noqa: E402

SLOT = 2                       # APF data slot 2: slot 1 is the cart
                               # itself (zeta/deploy.py's data.json)
IMG_WORDS = 256
CHUNK = 16                     # words per request
LANDING = 700                  # where a chunk lands in DMEM
OFFV, I, T, X0, YV = 16, 17, 18, 19, 20

DL = spec.DL_BASE
BASE_Y = 250
C_BAR = 0x20B040               # the green lion
C_TICK = 0xE6C010


def image():
    return [int(64 + 60 * math.sin(2 * math.pi * i / IMG_WORDS))
            for i in range(IMG_WORDS)]


def rows(addr, vals, per=16):
    return [f".sd {SLOT} {addr + off} "
            + " ".join(str(v) for v in vals[off:off + per])
            for off in range(0, len(vals), per)]


def build():
    L = []
    a = L.append
    a("; card.zol -- GENERATED by gen_card.py, do not edit")
    a("; content that never rode in the cart: the SD, a chunk at a time")
    a("")
    for name, v in (("GO", spec.SD_GO), ("SLOT", spec.SD_SLOT),
                    ("OFF", spec.SD_OFF), ("DST", spec.SD_DST),
                    ("LEN", spec.SD_LEN), ("OFFV", OFFV), ("I", I),
                    ("T", T), ("X0", X0), ("YV", YV)):
        a(f".const {name} {v}")
    a("")
    a(f".data {OFFV} 0")
    L.extend(rows(0, image()))
    a("")
    # ---- ask for the next chunk whenever the last one has landed --------
    a("load GO")
    a("jz issue")
    a("jmp draw")
    a("issue:")
    a(f"push {SLOT}")
    a("store SLOT")
    a("load OFFV")
    a("store OFF")
    a(f"push {LANDING}")
    a("store DST")
    a(f"push {CHUNK}")
    a("store LEN")
    a("push 1")
    a("store GO")
    a("load OFFV")                      # walk the image, wrapping
    a(f"push {CHUNK}")
    a("add")
    a(f"push {IMG_WORDS - 1}")
    a("and")
    a("store OFFV")
    a("draw:")
    # ---- the bars: one triangle per landed word -------------------------
    a(f"push {CHUNK}")
    a(f"store {DL}")
    a("push 0")
    a("store I")
    a("bar:")
    a("load I")                         # x0 = 20 + i*18
    a("push 18")
    a("mul")
    a("push 20")
    a("add")
    a("store X0")
    a("load I")                         # y = BASE_Y - word
    a(f"push {LANDING}")
    a("add")
    a("loadi")
    a(f"push {BASE_Y}")
    a("swap")
    a("sub")
    a("store YV")
    for k, expr in enumerate((["load X0"], [f"push {BASE_Y}"],
                              ["load X0", "push 14", "add"],
                              [f"push {BASE_Y}"],
                              ["load X0"], ["load YV"],
                              [f"push {C_BAR}"])):
        L.extend(expr)
        a("load I")
        a("push 7")
        a("mul")
        a(f"push {DL + 1 + k}")
        a("add")
        a("storei")
    a("load I")
    a("push 1")
    a("add")
    a("dup")
    a("store I")
    a(f"push {CHUNK}")
    a("lt")
    a("jz done")
    a("jmp bar")
    a("done:")
    a("halt")
    return L


if __name__ == "__main__":
    out = HERE / "card.zol"
    lines = build()
    out.write_text("\n".join(lines) + "\n")
    n = sum(1 for ln in lines if ln and not ln.startswith((";", ".")))
    print(f"wrote {out.name}: {n} instructions, "
          f"{IMG_WORDS} words on the card")
