#!/usr/bin/env python3
"""gen_edged.py -- writes carts/edged.zol: OBJ_EDGE's witness.

Three cubes turning over a checkered floor. The left and right ones are
OUTLINED; the middle one is the same mesh with the flag off, which is
what makes the outline read as a drawn line rather than as a different
model.

WHAT IS BEING PROVED, and it is three separate things:

  1. an outlined object against the ROOM has a line around it (its owner
     differs from the clear's owner, which is nobody);
  2. an outlined object against ANOTHER outlined object has a line
     between them -- the left and right cubes are placed to overlap, and
     "the owners differ" gives that with no special case;
  3. the unflagged cube has NO line anywhere, including where it touches
     an outlined one.

THE ERA DID THIS BY DRAWING EVERY MODEL TWICE, inflated and turned
inside out. Twice the geometry, and wrong at every sharp corner, because
an inflated hull does not know where the silhouette is. Here the
rasterizer already knows who owns each pixel; the line is a comparison
with the pixel to the left and the pixel above, riding the walk that was
already carrying the band out to the framebuffer. It costs no clocks.

Run me after changing anything: python3 carts/gen_edged.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from zeta import spec                          # noqa: E402
from gen_cube import cube_mesh, data_lines, ground_mesh   # noqa: E402

ONE = 65536
GROUND_AT, CUBE_AT = 512, 1400
# A BLACK LINE ON A NEAR-BLACK BACKDROP IS NOT A LINE. The first version
# of this cart drew 0x000000 over spec.CLEAR_RGB (0x101018), and measured
# across 30 frames that made 22% of the outline INVISIBLE -- while the
# 58% that lands between the two overlapping cubes is black against red
# and reads hard. A player saw the result and reported that the middle
# cube's outline looked thicker. It is not: measured over 60 rotations
# both cubes carry a 1.0-pixel line. What differed was CONTRAST, and the
# middle cube is the one the high-contrast seam belongs to.
#
# So the witness uses a colour visible against BOTH, and a real cart over
# a bright path-traced room can go back to black.
EDGE = 0xF8F8C0                  # visible on the backdrop AND on the cubes

_OBJ = [spec.OL_BASE + 1 + k * spec.OL_STRIDE for k in range(4)]

PROGRAM = """
; the three cubes turn together, so the outline is tested against every
; silhouette a box has rather than against one lucky pose
load A
push 5
add
push 1023
and
store A
load A
store {A1}
load A
store {A2}
load A
store {A3}
halt
"""


def main():
    g_verts, g_faces = ground_mesh(10, 1)
    c_verts, c_faces = cube_mesh()
    g_lines, g_len = data_lines(GROUND_AT, g_verts, g_faces)
    c_lines, c_len = data_lines(CUBE_AT, c_verts, c_faces)
    assert GROUND_AT + g_len <= CUBE_AT and CUBE_AT + c_len <= spec.DL_BASE

    E = spec.OBJ_CULL | spec.OBJ_EDGE
    objs = [
        (GROUND_AT, 0, 0, 0, 0, spec.OBJ_CULL),
        # the two outlined cubes OVERLAP, so the line between two
        # different owners is tested and not only the line against the room
        (CUBE_AT, int(-0.85 * ONE), 0, int(2.6 * ONE), 0, E),
        (CUBE_AT, int(0.15 * ONE), 0, int(2.2 * ONE), 0, E),
        (CUBE_AT, int(1.9 * ONE), 0, int(2.4 * ONE), 0, spec.OBJ_CULL),
    ]
    ol = " ".join(str(v) for o in objs for v in o)

    out = ["; edged.zol -- OBJ_EDGE's witness. GENERATED by carts/gen_edged.py",
           "; -- edit that, not this.",
           ";",
           "; Two overlapping outlined cubes and one unflagged one. The line",
           "; is drawn where a pixel's owner differs from the owner to its",
           "; left or above -- so it appears around each flagged cube AND",
           "; between them, and nowhere on the third.",
           "",
           ".const A 16",
           "",
           ".data 8 0 91750 -262144 0    ; camera: x 0, y 1.4, z -4",
           f".data {spec.EDGE_RGB} {EDGE}     ; the outline's colour",
           f".data {spec.AU_BASE + 4} 38448 6",
           "",
           f"; object list: {len(objs)} objects",
           f".data {spec.OL_BASE} {len(objs)} {ol}",
           "",
           f"; ---- ground mesh: {g_len} words ----"]
    out += g_lines
    out += ["", f"; ---- cube mesh: {c_len} words ----"] + c_lines
    out.append(PROGRAM.format(A1=_OBJ[1] + 4, A2=_OBJ[2] + 4,
                              A3=_OBJ[3] + 4))
    path = Path(__file__).parent / "edged.zol"
    path.write_text("\n".join(out))
    print(f"wrote {path}: {len(objs)} objects, ground {g_len}w, cube {c_len}w")


if __name__ == "__main__":
    main()
