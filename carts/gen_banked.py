#!/usr/bin/env python3
"""gen_banked.py -- writes carts/banked.zol: content that does not fit.

The first cart whose art lives OUTSIDE the resident image. Two meshes --
the Gouraud bunny and the flat cube -- sit in the cart's CRAM segment,
and the program pages whichever one it wants into the same DMEM slot
with the mover (spec.DMA_*). Press A for the cube, B for the bunny; the
swap costs four stores and one frame.

Resident DMEM holds only the ground, the object list and the program's
own variables, so the machine's 16K of fast memory stays free for the
working set while the content lives in eight megabytes of CRAM. That is
the whole point of capacity phase 2, in a cart you can watch.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from zeta import meshtool, spec                # noqa: E402
from gen_cube import ground_mesh, cube_mesh, data_lines as cube_lines  # noqa: E402

GROUND_AT = 320                # resident: the floor never changes
MESH_AT = 900                  # the paged slot: whichever mesh is current
X, Z, YAW, WANT, PHASE, PICK, IDX = 16, 17, 18, 19, 20, 21, 22


def mesh_words(verts, faces, cols=None):
    """A GEOM mesh block: [nv, nf, verts..., faces...]."""
    words = [len(verts) // 3, len(faces)]
    words += list(verts)
    for i, (a, b, c, col) in enumerate(faces):
        words += [a | (b << 10) | (c << 20), col]
    return words


def main():
    import json
    import subprocess
    out = subprocess.run(
        [sys.executable, "-c",
         "import sys, json; sys.path.insert(0, sys.argv[1]);"
         "from zeta.assets import bunny;"
         "print(json.dumps([bunny._raw_vertices(), bunny._raw_faces()]))",
         str(HERE.parent.parent / "zeta/src")],
        capture_output=True, text=True, check=True)
    bverts, bfaces = json.loads(out.stdout)
    # the FULL bunny: three chunks (the 256-vertex mesh cap), paged in
    # over three consecutive frames -- masked latency, the fabric's move
    blocks = meshtool.bake(bverts, bfaces, tint=(240, 240, 240), height=1.6,
                           gouraud=True, max_words=4200)
    assert all(len(b) <= spec.DMA_MAX for b in blocks), \
        [len(b) for b in blocks]
    cverts, cfaces = cube_mesh()
    cube = mesh_words(cverts, cfaces)

    # ---- the CRAM segment, CONTIGUOUS again (the restride, build 51):
    # the translation at the cram_fb boundary hides the chip's row tails
    # from every client, so content packs linearly -- the layout the
    # seam forbade for fifteen boots. One request per chunk; the mover's
    # long row-crossing reads are exactly the ops the restride legalized.
    cram = []  # emitted after slots are known

    g_verts, g_faces = cube_lines and ground_mesh()
    g_lines, g_len = cube_lines(GROUND_AT, g_verts, g_faces)
    assert GROUND_AT + g_len <= MESH_AT
    # DMEM slots for the three chunks, back to back above MESH_AT
    slots = []
    at = MESH_AT
    for b in blocks:
        slots.append(at); at += len(b)
    assert at <= spec.DL_BASE, at
    # the cube gets its OWN slot so nothing displayed is ever
    # overwritten again (the live-surgery lesson of boot 50)
    CUBE_SLOT = at
    at += len(cube)
    assert at <= spec.DL_BASE, at
    seg = []
    pieces = []
    def place(words, dst):
        pieces.append((len(seg), dst, len(words)))
        seg.extend(words)
    for k, b in enumerate(blocks):
        place(b, slots[k])
    place(cube, CUBE_SLOT)
    NBP, NCP = len(blocks), 1
    # the request table, resident: [src, dst, len] per piece
    TBL = 80
    table = []
    for src, dst, ln in pieces:
        table += [src, dst, ln]
    assert TBL + len(table) <= GROUND_AT, (TBL, len(table))
    for o in range(0, len(seg), 16):
        vals = " ".join(str(spec.s32(w)) for w in seg[o:o + 16])
        cram.append(f".cram {o} {vals}")
    tbl_lines = []
    for o in range(0, len(table), 12):
        vals = " ".join(str(v) for v in table[o:o + 12])
        tbl_lines.append(f".data {TBL + o} {vals}")

    head = [f"; banked.zol -- both meshes live in CRAM ({len(seg)} words);",
            "; the program pages one in at a time. GENERATED by",
            "; carts/gen_banked.py -- edit that, not this.",
            "", ".const PAD 1",
            f".const SRC {spec.DMA_SRC}", f".const DST {spec.DMA_DST}",
            f".const LEN {spec.DMA_LEN}", f".const GO {spec.DMA_GO}",
            f".const X {X}", f".const Z {Z}", f".const YAW {YAW}",
            f".const WANT {WANT}", f".const PHASE {PHASE}",
            f".const PICK {PICK}", f".const IDX {IDX}",
            "",
            ".data 8 0 91750 -196608 0     ; camera: y 1.4, z -3",
            f".data 16 0 98304 0 -1 0 0 0  ; pose, WANT=-1, PHASE, PICK, IDX",
            f".data {spec.AU_BASE + 4} 25000 5", ""]
    # object list: ground + up to three paged meshes sharing one pose.
    # OL count is switched by the program: 2 for the cube, 4 for the bunny.
    ol = [f".data {spec.OL_BASE} 1 {GROUND_AT} 0 0 0 0 1"]
    for k, sl in enumerate(slots):
        ol.append(f".data {spec.OL_BASE + 7 + k * 6} {sl} 0 0 98304 0 3")
    ol.append("")

    prog = [
        "; ---- pick: A wants the cube (1), B the bunny (0); an unloaded",
        "; ---- machine (WANT<0) wants the bunny. A change starts PHASE. --",
        "load WANT", "store PICK",
        "load PAD", "push 16", "and", "jz not_a",
        "push 1", "store PICK",
        "not_a:",
        "load PAD", "push 32", "and", "jz not_b",
        "push 0", "store PICK",
        "not_b:",
        "load WANT", "push 0", "lt", "jz have",
        "push 0", "store PICK",
        "have:",
        "; ---- boot: page EVERYTHING once (bunny + cube, own slots);",
        "; ---- afterwards A/B are pure display flips -- no mover, ever --",
        "load WANT", "push 0", "lt", "jz not_boot",
        f"push {NBP + NCP}", "store PHASE", "push 0", "store IDX",
        "push 0", "store WANT",
        "not_boot:",
        "load PHASE", "jz flips",
        "load IDX", "push 3", "mul", f"push {TBL}", "add",
        "dup", "loadi", "store SRC",
        "dup", "push 1", "add", "loadi", "store DST",
        "push 2", "add", "loadi", "store LEN",
        "push 1", "store GO",
        "load IDX", "push 1", "add", "store IDX",
        "load PHASE", "push 1", "sub", "store PHASE",
        "jmp drive",                        # floor only while paging
        "flips:",
        "load PICK", "store WANT",
        "load WANT", "jz show_bunny",
        f"push {CUBE_SLOT}", f"store {spec.OL_BASE + 7}",   # entry 1 ->
        "push 1", f"store {spec.OL_BASE + 7 + 5}",          # cube, flat
        "push 2", f"store {spec.OL_BASE}", "jmp drive",
        "show_bunny:",
        f"push {slots[0]}", f"store {spec.OL_BASE + 7}",    # entry 1 ->
        "push 3", f"store {spec.OL_BASE + 7 + 5}",          # chunk 1
        f"push {1 + len(blocks)}", f"store {spec.OL_BASE}",
        "drive:",
        "load PAD", "push 8", "and", "jz n_r",
        "load X", "push 3277", "add", "store X", "n_r:",
        "load PAD", "push 4", "and", "jz n_l",
        "load X", "push 3277", "sub", "store X", "n_l:",
        "load PAD", "push 1", "and", "jz n_u",
        "load Z", "push 3277", "add", "store Z", "n_u:",
        "load PAD", "push 2", "and", "jz n_d",
        "load Z", "push 3277", "sub", "store Z", "n_d:",
        "load YAW", "push 3", "add", "store YAW",
    ]
    for k in range(len(blocks)):                 # chunks share one pose
        base = spec.OL_BASE + 7 + k * 6
        prog += [f"load X", f"store {base + 1}",
                 f"load Z", f"store {base + 3}",
                 f"load YAW", f"store {base + 4}"]
    prog += ["halt"]

    (HERE / "banked.zol").write_text(
        "\n".join(head + ol + g_lines + tbl_lines + [""] + cram
                   + [""] + prog))
    print(f"wrote banked.zol: contiguous segment {len(seg)} words -- "
          f"bunny {NBP} chunks, cube {NCP}, table at {TBL}, "
          f"slots {slots} cube {CUBE_SLOT}")


if __name__ == "__main__":
    main()
