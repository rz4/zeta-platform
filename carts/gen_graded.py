#!/usr/bin/env python3
"""gen_graded.py -- writes carts/graded.zol: the curve's witness.

The same room, twice a second, under two different films.

  frames 0-63    the DIAGNOSTIC curve: red identity, green gamma 1.6,
                 blue gamma 0.7 -- three different curves in one table
  frames 64-127  a warm filmic curve: lifted blacks, rolled highlights,
                 red pushed and blue pulled

Both are the same framebuffer. Nothing in the scene changes, no plate is
reloaded, and the object list is identical. Only the 32 words at
GRADE_SRC change, and they change on ONE frame.

WHY THE DIAGNOSTIC MATTERS MORE THAN THE PRETTY ONE. A curve that alters
the picture proves the table is read; it does not prove the arithmetic
is right. The diagnostic's RED is the identity, so an index off by one
or a channel packed wrong shows up as red coming out wrong -- while a
handsome warm curve would still look handsome either way.

It all has to be in the FIRST frame, because glass scans three and no
more. A cart that saved its interesting half for frame 60 would be gated
on its dull half.

cross is blind to all of this, correctly: the framebuffer never changes.
glass is the gate.

Run me after changing anything: python3 carts/gen_graded.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from zeta import spec                          # noqa: E402
from gen_cube import cube_mesh, data_lines, ground_mesh   # noqa: E402

ONE = 65536
GROUND_AT, CUBE_AT = 512, 1400
TAB_A, TAB_B = 2200, 2240        # the two curves, resident


def level(c5):
    """The 8-bit value a 5-bit level has always become."""
    return (c5 << 3) | (c5 >> 2)


def probe_curve():
    """THE DIAGNOSTIC, and it has to fit in ONE frame because glass only
    ever scans the first three.

      red    IDENTITY -- a level goes in and the same level comes out.
             This is the exactness probe, and it is the one that catches
             an index off by one (red would come from the wrong level)
             and a channel packed wrong (red would pick up green's byte).
      green  gamma 1.6, darker through the middle
      blue   gamma 0.7, lighter through the middle

    Three different curves in one table, so a single scanned frame proves
    the levels are exact, that the table is actually READ, and that the
    channels are independent. A pretty curve proves only the middle one.
    """
    out = []
    for i in range(32):
        t = i / 31.0
        r = level(i)
        g = int(round((t ** 1.6) * 255))
        b = int(round((t ** 0.7) * 255))
        out.append((r << 16) | (g << 8) | b)
    return out


def warm_curve():
    """Lifted blacks, rolled highlights, red pushed and blue pulled --
    a print film, and the sort of thing nobody could do until about
    2005 because nobody had the picture in a pipeline on the way out."""
    out = []
    for i in range(32):
        t = i / 31.0
        s = t * t * (3 - 2 * t)             # smoothstep: the roll
        r = 0.06 + 0.94 * (0.35 * t + 0.65 * s) ** 0.88
        g = 0.05 + 0.90 * (0.45 * t + 0.55 * s)
        b = 0.09 + 0.78 * (0.60 * t + 0.40 * s) ** 1.18
        v = [max(0, min(255, int(round(x * 255)))) for x in (r, g, b)]
        out.append((v[0] << 16) | (v[1] << 8) | v[2])
    return out


def main():
    g_verts, g_faces = ground_mesh(10, 1)
    c_verts, c_faces = cube_mesh()
    g_lines, g_len = data_lines(GROUND_AT, g_verts, g_faces)
    c_lines, c_len = data_lines(CUBE_AT, c_verts, c_faces)
    assert GROUND_AT + g_len <= CUBE_AT and CUBE_AT + c_len <= TAB_A

    objs = [(GROUND_AT, 0, 0, 0, 0, spec.OBJ_CULL),
            (CUBE_AT, 0, 0, int(2.4 * ONE), 0, spec.OBJ_CULL),
            (CUBE_AT, int(-1.9 * ONE), 0, int(3.1 * ONE), 0, spec.OBJ_CULL),
            (CUBE_AT, int(1.9 * ONE), 0, int(3.1 * ONE), 0, spec.OBJ_CULL)]
    ol = " ".join(str(v) for o in objs for v in o)

    def tab(base, words):
        return [f".data {base + o} " + " ".join(str(w) for w in words[o:o + 8])
                for o in range(0, len(words), 8)]

    out = ["; graded.zol -- the curve's witness. GENERATED by",
           "; carts/gen_graded.py -- edit that, not this.",
           ";",
           "; The same room under two films, swapping every second. The",
           "; DIAGNOSTIC one is the gate -- red identity, green and blue",
           "; curved -- so one scanned frame proves the levels are exact,",
           "; the table is read, and the channels are independent. cross is",
           "; blind on purpose: the framebuffer never changes. glass is not.",
           "",
           ".const A 16",
           "",
           ".data 8 0 91750 -262144 0",
           f".data {spec.AU_BASE + 4} 38448 6",
           f".data {spec.GRADE_SRC} {TAB_A}",
           "",
           f".data {spec.OL_BASE} {len(objs)} {ol}",
           "",
           f"; ---- ground mesh: {g_len} words ----"]
    out += g_lines
    out += ["", f"; ---- cube mesh: {c_len} words ----"] + c_lines
    out += ["", "; ---- the diagnostic curve ----"] + tab(TAB_A, probe_curve())
    out += ["", "; ---- the warm curve ----"] + tab(TAB_B, warm_curve())
    out += ["", f"""
; the cubes turn, so the curve is judged over a moving picture
load A
push 4
add
push 1023
and
store A
load A
store {spec.OL_BASE + 1 + 1 * spec.OL_STRIDE + 4}
load A
store {spec.OL_BASE + 1 + 2 * spec.OL_STRIDE + 4}
load A
store {spec.OL_BASE + 1 + 3 * spec.OL_STRIDE + 4}

; swap the film every 60 frames: ONE store, no reload of anything else
load {spec.REG_FRAME}
push 64
and
jz ident
push {TAB_B}
store {spec.GRADE_SRC}
halt
ident:
push {TAB_A}
store {spec.GRADE_SRC}
halt
"""]
    path = Path(__file__).parent / "graded.zol"
    path.write_text("\n".join(out))
    print(f"wrote {path}: {len(objs)} objects, two 32-word curves")


if __name__ == "__main__":
    main()
