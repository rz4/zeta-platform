#!/usr/bin/env python3
"""gen_cardprobe.py -- writes carts/cardprobe.zol: where does a card read
actually stop?

Three black screens and a red one told us the console works and the card
delivers nothing. That is as far as colour can take us. cart_loader.v
solved the same problem at boots 17-23 by SIGNING ITS OWN DELIVERY --
writing counters into DMEM so the console could report its own boot
instead of us inferring it from artifacts. This is that, for the card.

The silicon now keeps five counters (spec.CARD_DIAG) and writes them
every frame. This cart displays them as bit rows, high bit on the left:

  row 0   ds_read pulses ISSUED       nonzero: the console asked, and the
                                      request crossed into the bridge clock
  row 1   ds_ack seen                 nonzero: the OS acknowledged the
                                      command -- it is listening
  row 2   ds_done seen                nonzero: the OS finished the command
  row 3   the OS's ERROR CODE         zero is OK; anything else is the OS
                                      telling us exactly what it refused
  row 4   bridge writes INTO OUR      nonzero: data arrived at 0x2xxxxxxx
          window, ungated
  row 5   bridge writes ANYWHERE      nonzero: the bridge is alive at all

Read them together and the fault names itself:

  all zero except row 5   the command never left -- the CDC or the pulse
  row 0 set, row 1 clear  the OS never heard us: wrong command shape
  row 1 set, row 2 clear  it heard us and never finished: it is stuck
  row 2 set, row 3 set    it refused, and row 3 says why
  row 2 set, row 4 clear  it says OK but wrote nowhere we can see:
                          the bridge address is wrong
  row 4 set, red screen   the words arrive and the FIFO loses them

A request goes out on frame 60 and every 120 frames after, so the rows
keep moving if anything is moving at all.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from zeta import spec                                    # noqa: E402

DL = spec.DL_BASE
ROW_Y = 8             # first row's top edge
ROW_H = 11            # bar height
ROW_GAP = 14
BIT_W = 16            # each bit is a 16px cell
BIT_GAP = 2
X0 = 24
C_ONE = 0xEEEEEE      # albedo: a set bit
C_ZERO = 0x2A2A33     # nigredo: a clear one
C_MARK = 0xE6C010     # citrinitas: the request went out this frame

NBITS = 8             # bits shown per row (counters are small)
ROWS = 11


def build():
    L = []
    a = L.append
    a("; cardprobe.zol -- GENERATED by gen_cardprobe.py, do not edit")
    a("; the card signs its own delivery; this reads the signature")
    a("")
    a(f".sd 2 0 64 124 178 218")
    a(f".data {600} 111 222 333 444")
    a(f".const GO {spec.SD_GO}")
    a(f".const SLOTC {spec.SD_SLOT}")
    a(f".const OFFC {spec.SD_OFF}")
    a(f".const DSTC {spec.SD_DST}")
    a(f".const LENC {spec.SD_LEN}")
    a(f".const D0 {spec.CARD_DIAG}")
    a(f".const D1 {spec.CARD_DIAG + 1}")
    a(f".const D2 {spec.CARD_DIAG + 2}")
    a(f".const D3 {spec.CARD_DIAG + 3}")
    a(f".const FRAME {spec.REG_FRAME}")
    a(".const V 600")
    a(".const T 16")
    a(".const BIT 17")
    a("")

    # ---- ask again every 120 frames, so nothing can look stuck by luck --
    a("load FRAME")
    a("push 127")          # a MASK, and 119 is not one: bit 3 is clear in
    a("and")               # 119, so (frame & 119) == 60 is true for NO
    a("push 60")           # frame, and the probe asked for nothing at all
    a("eq")
    a("jz noask")
    a("push 2")
    a("store SLOTC")
    a("push 0")
    a("store OFFC")
    a("push V")
    a("store DSTC")
    a("push 1")
    a("store LENC")
    a(f"push {spec.SD_READ}")   # a ONE-WORD READ: the wave demo read
    a("store GO")              # sixteen words fine, and save.zol
                               # so they report what APF
                               # does with a WRITE
    a("noask:")

    # ---- the display list ------------------------------------------------
    a(f"push {ROWS * NBITS * 2}")
    a(f"store {DL}")

    tri = 0
    for row in range(ROWS):
        y0 = ROW_Y + row * ROW_GAP
        y1 = y0 + ROW_H
        for bit in range(NBITS):
            # value = the row's counter, shifted down to this bit
            if row == 0:      # ds_read      diag0[7:0]
                a("load D0"); a(f"shr {bit}")
            elif row == 1:    # ds_ack       diag0[15:8]
                a("load D0"); a(f"shr {8 + bit}")
            elif row == 2:    # ds_done      diag0[23:16]
                a("load D0"); a(f"shr {16 + bit}")
            elif row == 3:    # err          diag0[26:24]
                a("load D0"); a(f"shr {24 + bit}")
            elif row == 4:    # window writes diag1[15:0]
                a("load D1"); a(f"shr {bit}")
            elif row == 5:    # any writes    diag1[31:16]
                a("load D1"); a(f"shr {16 + bit}")
            elif row == 6:    # CAPTURED into the FIFO   diag2[15:0]
                a("load D2"); a(f"shr {bit}")
            elif row == 7:    # APF's FIRST read address, low byte
                a("load D2"); a(f"shr {24 + bit}")
            elif row == 8:    # MEASURED latency, in frames
                a("load D3"); a(f"shr {bit}")
            elif row == 9:    # words the console COPIED into DMEM
                a("load D3"); a(f"shr {8 + bit}")
            else:             # the landed word itself
                a("load V"); a(f"shr {bit}")
            a("push 1")
            a("and")
            a("jz z%d_%d" % (row, bit))
            a(f"push {C_ONE}")
            a("jmp c%d_%d" % (row, bit))
            a("z%d_%d:" % (row, bit))
            a(f"push {C_ZERO}")
            a("c%d_%d:" % (row, bit))
            a("store T")
            x0 = X0 + (NBITS - 1 - bit) * (BIT_W + BIT_GAP)
            x1 = x0 + BIT_W
            for (px0, py0, px1, py1, px2, py2) in (
                    (x0, y0, x1, y0, x0, y1), (x1, y0, x1, y1, x0, y1)):
                base = DL + 1 + tri * spec.DL_STRIDE
                for k, v in enumerate((px0, py0, px1, py1, px2, py2)):
                    a(f"push {v}")
                    a(f"store {base + k}")
                a("load T")
                a(f"store {base + 6}")
                tri += 1
    a("halt")
    return L, tri


if __name__ == "__main__":
    lines, tri = build()
    out = HERE / "cardprobe.zol"
    out.write_text("\n".join(lines) + "\n")
    n = sum(1 for ln in lines if ln and not ln.startswith((";", ".")))
    print(f"wrote {out.name}: {n} instructions, {tri} triangles, "
          f"{ROWS} rows x {NBITS} bits")
