#!/usr/bin/env python3
"""gen_boot.py -- writes carts/boot.zol: the machine's face.

A console that boots straight into a cart is a dev board. This is the
thing Zeta shows when it wakes: the triangle, the checker world, the
glyph, and a chord -- roughly four seconds, then it holds.

The sequence is the machine's own history in order:

  0.0s  THE TRIANGLE.  One green-lion triangle grows from nothing on
        black. It is the first thing this machine ever drew (rung 1) and
        the only thing it can draw; everything else is more of it.

  1.0s  THE CHECKER WORLD.  The floor arrives in nigredo and albedo --
        the 8x8 plane from carts/gen_cube.py, unchanged -- and the camera
        pulls back through it. Flat black and white, because a checker is
        the cheapest pattern that proves perspective is real.

  2.2s  THE GLYPH.  Zeta, drawn as three citrinitas bars over the world:
        the upper stroke, the diagonal, the lower stroke.

  3.2s  THE CHORD.  Four wavetable voices on A = 432, which is not an
        affectation: 43.2 MHz is 400*360*60*5, the video law's own
        arithmetic, so one cycle of A is exactly 100,000 core clocks.
        The boot chord is this machine's clock made audible, and it is
        error-free by construction rather than by tuning.

THE PALETTE IS ALCHEMICAL (legislated at boot 61): nigredo black and
albedo white for the floor, and the accents in the stages of the work --
the green lion that begins it, citrinitas yellow, rubedo red. The machine
wears the colours of transmutation because that is what it is: base
silicon fixed, boot by boot, into the incorruptible.
"""
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from zeta import spec                                    # noqa: E402
from gen_cube import ground_mesh, data_lines             # noqa: E402

ONE = 65536
DL = spec.DL_BASE
GROUND_AT = 400
WAVE_AT = 340                  # the voice's page (WAV_WORDS words)

C_LION = 0x20B040              # the green lion, which begins the work
C_CITRIN = 0xE6C010            # citrinitas
C_RUBEDO = 0xC42020            # rubedo

T_TRI, T_WORLD, T_GLYPH, T_CHORD = 0, 60, 132, 192

# A = 432: one cycle is exactly 100,000 core clocks
CHORD = [216.0, 324.0, 432.0, 648.0]


def inc(f):
    return int(round(f * (1 << 24) / spec.SND_HZ))


def bell_page():
    """One cycle of fundamental + 3rd + 7th, packed four per word."""
    n = spec.WAV_W
    samples = []
    for i in range(n):
        t = 2 * math.pi * i / n
        v = (1.00 * math.sin(t) + 0.55 * math.sin(3 * t)
             + 0.30 * math.sin(7 * t))
        samples.append(max(-128, min(127, int(round(v * 127 / 1.85)))))
    out = []
    for w in range(spec.WAV_WORDS):
        v = 0
        for b in range(4):
            v |= (samples[w * 4 + b] & 0xFF) << (8 * b)
        out.append(v)
    return out


def quad(a, base, x0, y0, x1, y1, colour_ops):
    """Two triangles, corners as literals, colour from the stack."""
    for (px0, py0, px1, py1, px2, py2) in (
            (x0, y0, x1, y0, x0, y1), (x1, y0, x1, y1, x0, y1)):
        for k, v in enumerate((px0, py0, px1, py1, px2, py2)):
            a(f"push {v}")
            a(f"store {base + k}")
        for op in colour_ops:
            a(op)
        a(f"store {base + 6}")
        base += spec.DL_STRIDE
    return base


def build():
    L = []
    a = L.append
    a("; boot.zol -- GENERATED by gen_boot.py, do not edit")
    a("; the machine's face: triangle, world, glyph, chord")
    a("")
    a(f".const FRAME {spec.REG_FRAME}")
    a(f".const T 16")
    a(f".const S 17")
    a("")
    # the wave page, and the camera looking slightly down the z axis
    page = bell_page()
    for i in range(0, len(page), 16):
        a(f".data {WAVE_AT + i} " + " ".join(str(v) for v in page[i:i + 16]))
    a(f".data {spec.WAV_SRC} {WAVE_AT}")
    a(f".data {spec.CAM_X} 0 131072 -131072")     # y 2.0, z -2
    a(f".data {spec.CAM_PITCH} 96")               # tilted down, or the
                                                  # floor is a sliver
    a(f".data {spec.CAM_YAW} 0")
    verts, faces = ground_mesh()
    rows, _ = data_lines(GROUND_AT, verts, faces)   # (lines, word count)
    L.extend(rows)
    # the object list starts EMPTY: the world arrives on cue
    a(f".data {spec.OL_BASE} 0")
    a("")

    # ---- the world appears at T_WORLD, and the camera pulls back -------
    a(f"load FRAME")
    a(f"push {T_WORLD}")
    a("lt")
    a("jz world_on")
    a("jmp no_world")
    a("world_on:")
    a("push 1")                                   # one object: the floor
    a(f"store {spec.OL_BASE}")
    a(f"push {GROUND_AT}")
    a(f"store {spec.OL_BASE + 1}")
    a("push 0")
    a(f"store {spec.OL_BASE + 2}")
    a("push 0")
    a(f"store {spec.OL_BASE + 3}")
    a("push 0")
    a(f"store {spec.OL_BASE + 4}")
    a("push 0")
    a(f"store {spec.OL_BASE + 5}")
    a("push 1")                                   # OBJ_CULL
    a(f"store {spec.OL_BASE + 6}")
    a("load FRAME")                               # ...and pulls BACK,
    a(f"push {T_WORLD}")                          # away from the world
    a("sub")
    a("push 1536")
    a("mul")
    a("push -131072")
    a("swap")
    a("sub")
    a(f"store {spec.CAM_Z}")
    a("no_world:")

    # ---- the chord at T_CHORD ------------------------------------------
    a("load FRAME")
    a(f"push {T_CHORD}")
    a("lt")
    a("jz chord_on")
    a("jmp no_chord")
    a("chord_on:")
    for c, f in enumerate(CHORD):
        a(f"push {inc(f)}")
        a(f"store {spec.AU_BASE + 2 * c}")
        a(f"push {10 | spec.AU_WAVE}")
        a(f"store {spec.AU_BASE + 2 * c + 1}")
    a("no_chord:")

    # ---- the display list ----------------------------------------------
    # the triangle grows for the first second; the glyph arrives at T_GLYPH
    a("load FRAME")
    a(f"push {T_GLYPH}")
    a("lt")
    a("jz glyph")
    # --- the triangle alone ---
    a("push 1")
    a(f"store {DL}")
    a("load FRAME")                               # half-width = frame*2,
    a("push 2")                                   # capped by the phase
    a("mul")
    a("push 1")
    a("add")
    a("store T")
    a("push 160")                                 # apex
    a(f"store {DL + 1}")
    a("push 80")
    a(f"store {DL + 2}")
    a("push 160")                                 # right foot
    a("load T")
    a("add")
    a(f"store {DL + 3}")
    a("push 200")
    a(f"store {DL + 4}")
    a("push 160")                                 # left foot
    a("load T")
    a("sub")
    a(f"store {DL + 5}")
    a("push 200")
    a(f"store {DL + 6}")
    a(f"push {C_LION}")
    a(f"store {DL + 7}")
    a("halt")

    # --- the glyph: three citrinitas bars, zeta ---
    a("glyph:")
    a("push 6")
    a(f"store {DL}")
    base = DL + 1
    base = quad(a, base, 96, 60, 224, 76, [f"push {C_CITRIN}"])   # upper
    base = quad(a, base, 150, 76, 176, 172, [f"push {C_CITRIN}"])  # diagonal
    base = quad(a, base, 96, 172, 224, 188, [f"push {C_RUBEDO}"])  # lower
    a("halt")
    return L


if __name__ == "__main__":
    out = HERE / "boot.zol"
    lines = build()
    out.write_text("\n".join(lines) + "\n")
    n = sum(1 for ln in lines if ln and not ln.startswith((";", ".")))
    print(f"wrote {out.name}: {n} instructions")
